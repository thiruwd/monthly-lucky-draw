-- A private schema keeps this application separate from existing Supabase apps.
CREATE SCHEMA IF NOT EXISTS lucky_draw;
REVOKE ALL ON SCHEMA lucky_draw FROM PUBLIC;
CREATE TABLE IF NOT EXISTS lucky_draw.draw_lock (id smallint PRIMARY KEY CHECK (id = 1));
INSERT INTO lucky_draw.draw_lock (id) VALUES (1) ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS lucky_draw.members (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_code varchar(50), name varchar(150) NOT NULL,
  email varchar(255), is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), deleted_at timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_draw_member_code ON lucky_draw.members (lower(member_code)) WHERE member_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_draw_members_active ON lucky_draw.members (is_active, id) WHERE deleted_at IS NULL;
CREATE TABLE IF NOT EXISTS lucky_draw.winners (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id bigint NOT NULL REFERENCES lucky_draw.members(id) ON DELETE RESTRICT,
  name varchar(150) NOT NULL, draw_month smallint NOT NULL CHECK (draw_month BETWEEN 1 AND 12),
  draw_year smallint NOT NULL CHECK (draw_year BETWEEN 2000 AND 9999), won_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(), CONSTRAINT uq_draw_member_period UNIQUE (member_id, draw_month, draw_year)
);
CREATE INDEX IF NOT EXISTS idx_draw_winners_period ON lucky_draw.winners (draw_year, draw_month, won_at DESC, id DESC);
CREATE TABLE IF NOT EXISTS lucky_draw.admins (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(80) NOT NULL, password_hash varchar(255) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_draw_admin_username ON lucky_draw.admins (lower(username));
CREATE TABLE IF NOT EXISTS lucky_draw.sessions (
  token_hash char(64) PRIMARY KEY, admin_id bigint NOT NULL REFERENCES lucky_draw.admins(id) ON DELETE CASCADE,
  csrf_token char(64) NOT NULL, expires_at timestamptz NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_draw_session_expiry ON lucky_draw.sessions (expires_at);
CREATE TABLE IF NOT EXISTS lucky_draw.requests (
  admin_id bigint NOT NULL REFERENCES lucky_draw.admins(id) ON DELETE RESTRICT,
  request_key varchar(64) NOT NULL, response_json jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY (admin_id, request_key)
);
CREATE TABLE IF NOT EXISTS lucky_draw.live_display (
  id smallint PRIMARY KEY CHECK (id = 1), data jsonb NOT NULL, updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE lucky_draw.draw_lock ENABLE ROW LEVEL SECURITY;
ALTER TABLE lucky_draw.members ENABLE ROW LEVEL SECURITY;
ALTER TABLE lucky_draw.winners ENABLE ROW LEVEL SECURITY;
ALTER TABLE lucky_draw.admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE lucky_draw.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE lucky_draw.requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE lucky_draw.live_display ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA lucky_draw FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA lucky_draw FROM PUBLIC;
